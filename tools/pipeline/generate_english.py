#!/usr/bin/env python3
"""Compile the reviewed English catalogue to bounded, read-only lookup tables.

The hash index does not duplicate Chinese literals in Flash. Two independent
hashes (32+16 bits, including byte length) identify each entry; generation rejects
collisions. Text is deduplicated behind 16-bit offsets, without runtime allocation.
The source catalogue remains readable and reviewable in data/i18n/en.json.
"""
import argparse, hashlib, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'data/i18n'
MAIN = ROOT / 'firmware/main'
OUTPUT = MAIN / 'language_english.h'
FONT = MAIN / 'language_latin.h'

def font(check):
    metadata=json.loads((DATA/'english_names.json').read_text())
    for local,source in [('gold_font.png','gfx/font/font.png'),('gold_charmap.asm','constants/charmap.asm')]:
        assert hashlib.sha256((DATA/local).read_bytes()).hexdigest()==metadata['files'][source]
    if check:
        meta=json.loads((DATA/'latin_glyphs.json').read_text())
        assert hashlib.sha256(FONT.read_bytes()).hexdigest()==meta['sha256']
        return
    from PIL import Image
    im=Image.open(DATA/'gold_font.png').convert('RGB')
    chars={c:int(code,16)-128 for c,code in re.findall(r'charmap "([^"\n])",\s*\$([0-9a-f]+)',(DATA/'gold_charmap.asm').read_text()) if 128<=int(code,16)<=255}
    extras={' ':['00000000']*8,
            '+':['00000000','00010000','00010000','01111100','00010000','00010000','00000000','00000000'],
            '=':['00000000','00000000','01111100','00000000','01111100','00000000','00000000','00000000'],
            '%':['01100010','01100100','00001000','00010000','00100110','01000110','00000000','00000000'],
            '*':['00000000','01010100','00111000','01111100','00111000','01010100','00000000','00000000'],
            '_':['00000000']*6+['01111110','00000000']}
    base=(ROOT/'assets/font16.bin').read_bytes();cnt=int.from_bytes(base[10:14],'little')
    codes=[int.from_bytes(base[14+i*2:16+i*2],'little') for i in range(cnt)]
    out=['// Gold Latin tiles, resampled vertically to 12px inside a 16px cell.',
         '// Provenance and source hashes: data/i18n/english_names.json.', '#pragma once',
         'static const uint8_t language_latin_pixels[95][32] = {']
    for c in map(chr,range(32,127)):
        if c in chars:
            n=chars[c];tile=[[sum(im.getpixel(((n%16)*8+x,(n//16)*8+y)))<384 for x in range(8)] for y in range(8)]
        elif c in extras:tile=[[bit=='1' for bit in row] for row in extras[c]]
        else:
            idx=codes.index(ord(c)) if ord(c) in codes else codes.index(ord('?'))
            g=base[14+cnt*2+idx*32:14+cnt*2+(idx+1)*32]
            tile=[[bool(g[y*4+(x+4)//8]&(128>>((x+4)%8))) for x in range(8)] for y in range(8)]
        pixels=[]
        for y in range(16):
            bits=0
            if 2<=y<14:
                for x in range(8):
                    if tile[(y-2)*8//12][x]:bits|=1<<(11-x)
            pixels.extend([bits>>8,bits&255])
        out.append(' {'+','.join(f'0x{b:02x}' for b in pixels)+'},')
    out+=['};',''];FONT.write_text('\n'.join(out))
    (DATA/'latin_glyphs.json').write_text(json.dumps({'source':metadata['source'],'width':8,'ink_height':12,'cell_height':16,'glyphs':95,'sha256':hashlib.sha256(FONT.read_bytes()).hexdigest()},indent=2)+'\n')

def hashes(text):
    a, b = 2166136261, 5381
    for c in text.encode():
        a = ((a ^ c) * 16777619) & 0xffffffff
        b = (b * 33 + c) & 0xffffffff
    return a, b, len(text.encode())

def formats(text):
    return re.findall(r'%(?!%)(?:[-+ #0]*)(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:ll|l|z)?[diuxXosc]', text.replace('%%', ''))

def generate():
    rows = json.loads((DATA / 'en.json').read_text())
    names = json.loads((DATA / 'english_names.json').read_text())
    entries = []; pool = []; offsets = {}; pool_bytes = 0
    seen = set()
    for source, target in rows.items():
        assert source and target and '\0' not in source + target
        assert all(ord(c) < 128 for c in target), (source, target)
        if formats(source) or '%%' in source:
            assert formats(source) == formats(target), (source, target, formats(source), formats(target))
        a,b,n = hashes(source); key=(a,(b^(n*2654435761))&0xffff)
        assert key not in seen, ('translation collision', source)
        seen.add(key)
        if target not in offsets:
            offsets[target]=pool_bytes;pool.append(target);pool_bytes+=len(target)+1
        entries.append((*key, offsets[target]))
    assert pool_bytes<65536, 'English string pool exceeds 16-bit offsets'
    out = ['// Generated by generate_english.py; review data/i18n/en.json.', '#pragma once',
           'static const char language_english_pool[] =']
    out += [json.dumps(value)[:-1]+'\\0"' for value in pool]
    out += [';', 'static const struct { uint32_t hash; uint16_t check,offset; } language_english[] = {']
    for a,b,offset in sorted(entries):
        out.append(f' {{0x{a:08x},0x{b:04x},{offset}}},')
    out += ['};']
    for key, table in [('pokemon','language_english_species'), ('moves','language_english_moves')]:
        assert len(names[key]) == 251
        out += [f'static const char *const {table}[252] = {{NULL,']
        out += [json.dumps(s)+',' for s in names[key]]
        out += ['};']
    out += ['']
    return '\n'.join(out)

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    source=generate()
    if args.check: assert OUTPUT.read_text()==source,'Regenerate language_english.h'
    else: OUTPUT.write_text(source)
    font(args.check)
    print(json.dumps({'english_strings':len(json.loads((DATA/'en.json').read_text())), 'header_sha256':hashlib.sha256(source.encode()).hexdigest()}))

if __name__ == '__main__': main()
