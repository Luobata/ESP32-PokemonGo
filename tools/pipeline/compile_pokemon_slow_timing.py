#!/usr/bin/env python3
"""Compile Crystal ANIM_MON_SLOW timing from the pinned, recorded ASM commands.
Only timing metadata is added: atlas pictures and normal/menu rates are untouched.
"""
import argparse,json
from pathlib import Path
from convert_pokemon_animation import timeline
ROOT=Path(__file__).resolve().parents[2]
def generate():
 data=json.loads((ROOT/'assets/pokemon_animation_sources.json').read_text())
 records=[];runs=[]
 for species in data['species']:
  commands=[tuple(c) for c in species['commands']]
  # PokeAnim_Setup2 sets b=4. GetDuration rounds EACH frame command down;
  # scaling merged runs or the final elapsed clock by 1.25 is not equivalent.
  commands=[(op,*args[:1],args[1]+args[1]//4) if op=='frame' else (op,*args) for op,*args in commands]
  seq=timeline(commands,species['frame_count'])
  records.append((len(runs),len(seq),seq[-1][0]));runs.extend(seq)
 lines=['// Generated by compile_pokemon_slow_timing.py from pinned Crystal commands.',
        '#pragma once','typedef struct { uint16_t start, count, ticks; } pokemon_slow_record_t;',
        'static const pokemon_anim_run_t POKEMON_SLOW_RUNS[] = {']
 lines += [f' {{{end},{frame}}},' for end,frame in runs]+['};','static const pokemon_slow_record_t POKEMON_SLOW_RECORDS[] = {']
 lines += [f' {{{start},{count},{ticks}}},' for start,count,ticks in records]+['};','']
 return '\n'.join(lines)
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 path=ROOT/'firmware/main/pokemon_slow_timing.h';text=generate()
 if args.check:assert path.read_text()==text
 else:path.write_text(text)
 print('Crystal per-command slow timing: 251 species')
