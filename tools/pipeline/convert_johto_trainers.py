#!/usr/bin/env python3
"""Pack eight original Crystal gym leaders and Elm overworld portrait without altering existing art IDs."""
from pathlib import Path
import argparse,hashlib,json,subprocess
from PIL import Image
ROOT=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser();p.add_argument('--crystal',type=Path,default=Path('/tmp/pokewalk-johto-crystal'));a=p.parse_args()
commit=subprocess.check_output(['git','-C',str(a.crystal),'rev-parse','HEAD'],text=True).strip()
lines=['// Generated by convert_johto_trainers.py; see assets/johto_trainer_sources.json.','#pragma once'];meta=[]
for i,name in enumerate(('falkner','bugsy','whitney','morty','chuck','jasmine','pryce','clair','elm')):
 path=a.crystal/('gfx/sprites' if name=='elm' else 'gfx/trainers')/f'{name}.png';im=Image.open(path).convert('RGB')
 if name=='elm':
  sprite=im.crop((0,0,16,16)).resize((48,48),Image.Resampling.NEAREST);im=Image.new('RGB',(56,56),'white');im.paste(sprite,(4,4))
 assert im.size==(56,56)
 colors=sorted(set(im.getdata()),key=sum);assert len(colors)==4
 pix=list(im.getdata());data=[sum(colors.index(pix[j+k])<<(6-k*2) for k in range(4)) for j in range(0,len(pix),4)]
 lines += ['static const uint8_t JOHTO_ART_%u[] = {%s};'%(i,','.join(map(str,data))),'static const uint16_t JOHTO_PAL_%u[] = {%s};'%(i,','.join(str((r>>3)<<11|(g>>2)<<5|(b>>3)) for r,g,b in colors))]
 meta.append({'class':name,'url':f'https://github.com/pret/pokecrystal/blob/{commit}/{path.relative_to(a.crystal)}','sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
lines+=['static const uint8_t *const JOHTO_TRAINER_ART[]={'+','.join(f'JOHTO_ART_{i}' for i in range(9))+'};','static const uint16_t *const JOHTO_TRAINER_PAL[]={'+','.join(f'JOHTO_PAL_{i}' for i in range(9))+'};']
# TrainerCard_JohtoBadgesOAM uses four tiles per face. The source sheet puts
# Mineral before Storm; our campaign visits Chuck before Jasmine.
badge_path=a.crystal/'gfx/trainer_card/badges.png';badges=Image.open(badge_path).convert('RGB')
badge_colors=sorted(set(badges.getdata()),key=sum);assert len(badge_colors)==4
for i,source_row in enumerate((0,1,2,3,5,4,6,7)):
 pixels=list(badges.crop((0,source_row*16,16,source_row*16+16)).getdata())
 packed=[sum(badge_colors.index(pixels[j+k])<<(6-k*2) for k in range(4)) for j in range(0,len(pixels),4)]
 lines+=['static const uint8_t JOHTO_BADGE_%u[]={%s};'%(i,','.join(map(str,packed)))]
lines+=['static const uint8_t *const JOHTO_BADGE_ART[]={'+','.join(f'JOHTO_BADGE_{i}' for i in range(8))+'};']
meta.append({'class':'badges','url':f'https://github.com/pret/pokecrystal/blob/{commit}/gfx/trainer_card/badges.png','sha256':hashlib.sha256(badge_path.read_bytes()).hexdigest(),'campaign_rows':[0,1,2,3,5,4,6,7]})
(ROOT/'firmware/main/johto_trainer_assets.h').write_text('\n'.join(lines)+'\n');(ROOT/'assets/johto_trainer_sources.json').write_text(json.dumps(meta,indent=2)+'\n')

# Original egg frame, centered by the shared renderer; source frame stays 40x40.
p=a.crystal/'gfx/pokemon/egg/front.png';im=Image.open(p).convert('RGB').crop((0,0,40,40))
colors=sorted(set(im.getdata()),key=sum);assert len(colors)==4
pixels=list(im.getdata());packed=[sum(colors.index(pixels[j+k])<<(6-k*2) for k in range(4)) for j in range(0,len(pixels),4)]
(ROOT/'firmware/main/johto_egg_assets.h').write_text('// Generated from pret/pokecrystal '+commit+' gfx/pokemon/egg/front.png frame 0.\n#pragma once\nstatic const uint8_t JOHTO_EGG_ART[]={'+','.join(map(str,packed))+'};\nstatic const uint16_t JOHTO_EGG_PAL[]={0,0x6b4d,0xdedb,0xffff};\n')
