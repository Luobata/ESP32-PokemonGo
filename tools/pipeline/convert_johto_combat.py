#!/usr/bin/env python3
"""Append pinned Crystal Gen II stats/learning without rewriting Gen I eligibility."""
import argparse,json
from pathlib import Path
from convert_johto import catalog,ROOT
from convert_pokemon_art import PinnedTree,COMMIT
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--src',type=Path,required=True);a=p.parse_args()
rows=catalog(PinnedTree(a.src))
metadata={m['id']:m for m in json.loads((ROOT/'data/pokemon_moves/gold_silver.json').read_text())['moves']}
supported=set(range(1,166))|{m['id'] for m in json.loads((ROOT/'data/pokemon_moves/selected_gen2.json').read_text())}
hm={15:15,19:25,57:25,70:20,148:10,250:20,127:35}
parents={e['target']:r['id'] for r in rows for e in r['evolutions'] if e['target']>151}
learn=[];ranges=[];pending={}
for r in rows[151:]:
 known={}
 for lv,mid in r['level_up']:
  if mid in supported:known[mid]=min(known.get(mid,255),lv)
 for mid in r['tm_hm']:
  if mid not in supported:continue
  power=metadata[mid]['power'];lv=hm.get(mid,20 if not power else 15 if power<=60 else 25 if power<=90 else 40)
  known[mid]=min(known.get(mid,255),lv)
 seq=sorted((lv,mid) for mid,lv in known.items());ranges.append((len(learn),len(seq)));learn+=seq
 pending[r['id']]=sorted(({m for _,m in r['level_up']}|set(r['tm_hm']))-supported)
text=['// Generated by convert_johto_combat.py from pret/pokecrystal '+COMMIT+'.','#pragma once',
 'static const uint8_t COMBAT_JOHTO_STATS[100][6] = {'+','.join('{'+','.join(map(str,r['stats']))+'}' for r in rows[151:])+'};',
 'static const uint8_t COMBAT_JOHTO_PARENTS[100] = {'+','.join(str(parents.get(r['id'],0)) for r in rows[151:])+'};',
 'static const uint16_t COMBAT_JOHTO_RANGES[100][2] = {'+','.join('{%d,%d}'%v for v in ranges)+'};',
 'static const uint8_t COMBAT_JOHTO_LEARN[][2] = {'+','.join('{%d,%d}'%v for v in learn)+'};']
(ROOT/'firmware/main/combat_johto.h').write_text('\n'.join(text)+'\n')
(ROOT/'assets/johto_combat_sources.json').write_text(json.dumps({'commit':COMMIT,'species':100,'supported_moves':sorted(supported),'pending_moves_by_species':pending,'policy':'Existing Gen I eligibility untouched; new species Crystal level/TM/HM only; unsupported special species not spawned.'},indent=2)+'\n')
print('Gen II rows',len(ranges),'learning records',len(learn))
