#!/usr/bin/env python3
"""Build bounded, offline traditional-Chinese tables from pinned OpenCC data.

Only glyphs and dictionary entries used by this game's text are linked. No heap,
network request or full OpenCC engine is needed on the device. Same-length BMP
conversion preserves the existing fixed-width wrapping and animation timing.
"""
import argparse, hashlib, json, re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
DATA=ROOT/'data/i18n'
MAIN=ROOT/'firmware/main'

def dictionaries():
 manifest=json.loads((DATA/'opencc/sources.json').read_text())
 for name,info in manifest['files'].items():
  assert hashlib.sha256((DATA/'opencc'/name).read_bytes()).hexdigest()==info['sha256'],name
 def read(name):
  return {a:b.split(' ')[0] for line in (DATA/'opencc'/name).read_text().splitlines() if line and not line.startswith('#') for a,b in [line.split('\t',1)]}
 chars=read('STCharacters.txt');phrases=read('STPhrases.txt')
 phrases.update(json.loads((DATA/'overrides.json').read_text()))
 return chars,phrases

def corpus():
 texts=[]
 for path in sorted([*MAIN.glob('*.c'),*MAIN.glob('*.h')]):
  if path.name in ('language_data.h','language_glyphs.h','language_english.h','language_latin.h','language_japanese.h','language_japanese_glyphs.h'):continue
  # Consume comments and literals together, so http:// inside a string is not
  # misclassified as a comment and cannot hide later Chinese text.
  tokens=re.finditer(r'"((?:[^"\\]|\\.)*)"|/\*.*?\*/|//[^\n]*',path.read_text(),re.S)
  texts += [m.group(1) for m in tokens if m.group(1) is not None]
 for name in ('gen1.bin','moves.bin'):
  # Extract all Chinese runs from the immutable asset name pools; binary bytes
  # outside the pools can only add unused guards/glyphs, never omit a name.
  texts += re.findall(r'[\u3400-\u9fff]+',(ROOT/'assets'/name).read_bytes().decode('utf-8',errors='ignore'))
 texts += list(json.loads((DATA/'overrides.json').read_text()))
 return sorted(set(t for t in texts if any('\u3400'<=c<='\u9fff' for c in t)))

def tables():
 chars,phrases=dictionaries();texts=corpus();joined='\0'.join(texts)
 used_chars=set(''.join(texts))
 chars={a:b for a,b in chars.items() if a in used_chars and a!=b}
 phrases={a:b for a,b in phrases.items() if a in joined}
 for a,b in [*chars.items(),*phrases.items()]:
  assert len(a)==len(b) and all(ord(c)<65536 for c in a+b),(a,b)
  assert len(a.encode())==len(b.encode()),(a,b)
  assert all(len(x.encode())==len(y.encode()) for x,y in zip(a,b)),(a,b)
  assert len(a.encode())<=255,(a,b)
 groups={}
 for a,b in phrases.items():
  assert ord(a[0])>=0x3400,'ASCII-leading phrase needs runtime support: '+a
  groups.setdefault(a[0],[]).append((a,b))
 for entries in groups.values():entries.sort(key=lambda v:(-len(v[0]),v[0]))
 def convert(text):
  out=[];i=0
  while i<len(text):
   found=next(((a,b) for a,b in groups.get(text[i],[]) if text.startswith(a,i)),None)
   if found:a,b=found;out.append(b);i+=len(a)
   else:out.append(chars.get(text[i],text[i]));i+=1
  return ''.join(out)
 target_chars=sorted({c for t in texts for c in convert(t) if '\u3400'<=c<='\u9fff'})
 return chars,groups,texts,target_chars,convert

def generate(check=False):
 chars,groups,texts,glyph_chars,convert=tables()
 header=['// Generated by tools/pipeline/generate_traditional.py. OpenCC 1.1.9 (Apache-2.0).',
         '// Source/license: data/i18n/opencc/. Game-specific overrides: data/i18n/overrides.json.',
         '#pragma once','static const struct { uint16_t from,to; } language_chars[] = {']
 header += [f' {{0x{ord(a):04x},0x{ord(b):04x}}},' for a,b in sorted(chars.items())]
 header+=['};','static const struct { const char *from,*to; uint8_t bytes; } language_phrases[] = {']
 ranges=[];index=0
 for first,entries in sorted(groups.items()):
  ranges.append((ord(first),index,len(entries)))
  for a,b in entries:header.append(f' {{{json.dumps(a,ensure_ascii=False)},{json.dumps(b,ensure_ascii=False)},{len(a.encode())}}},')
  index+=len(entries)
 header+=['};','static const struct { uint16_t first,start,count; } language_phrase_groups[] = {']
 header += [f' {{0x{a:04x},{b},{c}}},' for a,b,c in ranges]
 header+=['};','']
 # Keep original simplified glyphs byte-for-byte. This independent Taiwan face
 # is used only for traditional text; ASCII continues using the original font.
 glyphs=['// Generated by generate_traditional.py; PingFang TC Regular, 16x16, 1bpp.',
         '#pragma once','static const uint16_t language_glyph_codes[] = {',
         ','.join(f'0x{ord(c):04x}' for c in glyph_chars),'};',
         'static const uint8_t language_glyph_pixels[][32] = {']
 if check:
  # CI validates the committed glyphs without requiring a macOS system font.
  # Regeneration records their SHA and source face; changing corpus coverage
  # still fails here until the complete font has been regenerated.
  existing=(MAIN/'language_glyphs.h').read_text()
  meta=json.loads((DATA/'glyphs.json').read_text())
  assert hashlib.sha256(existing.encode()).hexdigest()==meta['sha256'],'Traditional glyph integrity'
  codes=[int(x,16) for x in re.findall(r'0x([0-9a-f]{4})',existing.split('language_glyph_pixels')[0])]
  assert codes==list(map(ord,glyph_chars)),'Regenerate traditional glyph coverage'
  pixels=bytes(int(x,16) for x in re.findall(r'0x([0-9a-f]{2})\b',existing.split('language_glyph_pixels')[1]))
  assert len(pixels)==len(codes)*32
 else:
  from PIL import ImageFont
  from convert_font import render_glyph
  font_path=Path('/System/Library/Fonts/PingFang.ttc')
  font=ImageFont.truetype(str(font_path),16,index=1)
  assert font.getname()[0]=='PingFang TC',font.getname()
  pixels=b''.join(render_glyph(font,c) for c in glyph_chars)
 for i,c in enumerate(glyph_chars):
  g=pixels[i*32:(i+1)*32];assert len(g)==32 and any(g),f'Empty traditional glyph: {c}'
  glyphs.append(' {'+','.join(f'0x{b:02x}' for b in g)+'},')
 glyphs+=['};','']
 if not check:
  (DATA/'glyphs.json').write_text(json.dumps({'font':'PingFang TC Regular','font_index':1,'size':16,'font_sha256':hashlib.sha256(font_path.read_bytes()).hexdigest(),'glyphs':len(glyph_chars),'sha256':hashlib.sha256('\n'.join(glyphs).encode()).hexdigest()},indent=2)+'\n')
 return {'language_data.h':'\n'.join(header),'language_glyphs.h':'\n'.join(glyphs)}, {'strings':len(texts),'characters':len(chars),'phrases':index,'glyphs':len(glyph_chars),'glyph_bytes':len(glyph_chars)*34}

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 output,stats=generate(args.check)
 for name,content in output.items():
  path=MAIN/name
  if args.check:assert path.read_text()==content,'Regenerate traditional text tables: '+name
  else:path.write_text(content)
 print(json.dumps(stats))
if __name__=='__main__':main()
