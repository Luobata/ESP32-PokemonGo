#!/usr/bin/env python3
"""Build the reviewed Japanese catalogue and a fixed Japanese-face glyph subset.

Translations/names are read-only Flash, as in English. No decompression cache,
heap allocation or save-layout change is required. --check needs no OS font.
"""
import argparse, hashlib, json, re, unicodedata
from pathlib import Path
from generate_english import ROOT, DATA, MAIN, hashes, formats

OUTPUT = MAIN / 'language_japanese.h'
FONT = MAIN / 'language_japanese_glyphs.h'

def generate():
    rows = json.loads((DATA/'ja.json').read_text())
    names = json.loads((DATA/'japanese_names.json').read_text())
    entries, pool, offsets, seen = [], [], {}, set()
    size = 0
    for source, target in rows.items():
        assert source and target and '\0' not in source+target
        assert unicodedata.normalize('NFC', target)==target, (source,target)
        assert all(ord(c)<65536 for c in target), source
        if formats(source) or '%%' in source:
            assert formats(source)==formats(target), (source,target,formats(source),formats(target))
        a,b,n=hashes(source);key=a,(b^(n*2654435761))&65535
        assert key not in seen, ('Japanese translation collision',source)
        seen.add(key)
        if target not in offsets:
            offsets[target]=size;pool.append(target);size+=len(target.encode())+1
        entries.append((*key,offsets[target]))
    assert size<65536, 'Japanese pool exceeds uint16 offsets'
    out=['// Generated by generate_japanese.py; review data/i18n/ja.json.',
         '#pragma once','static const char language_japanese_pool[] =']
    out += [json.dumps(v,ensure_ascii=False)[:-1]+'\\0"' for v in pool]
    out += [';', 'static const language_translation_t language_japanese[] = {']
    out += [f' {{0x{a:08x},0x{b:04x},{o}}},' for a,b,o in sorted(entries)]
    out += ['};']
    for key,label in [('pokemon','species'),('moves','moves')]:
        assert len(names[key])==251
        out += [f'static const char *const language_japanese_{label}[252] = {{NULL,']
        out += [json.dumps(s,ensure_ascii=False)+',' for s in names[key]]
        out += ['};']
    return '\n'.join(out)+'\n'

def glyph_codes():
    rows=json.loads((DATA/'ja.json').read_text())
    names=json.loads((DATA/'japanese_names.json').read_text())
    return sorted({ord(c) for s in [*rows.values(),*names['pokemon'],*names['moves']] for c in s if ord(c)>=128})

def font(check):
    codes=glyph_codes()
    if check:
        data=FONT.read_text();meta=json.loads((DATA/'japanese_glyphs.json').read_text())
        assert hashlib.sha256(data.encode()).hexdigest()==meta['sha256']
        actual=[int(x,16) for x in re.findall(r'0x([0-9a-f]{4})',data.split('language_japanese_pixels')[0])]
        assert actual==codes, 'Regenerate Japanese glyphs'
        pixels=bytes(int(x,16) for x in re.findall(r'0x([0-9a-f]{2})\b',data.split('language_japanese_pixels')[1]))
        assert len(pixels)==len(codes)*32
        for i,c in enumerate(codes):assert any(pixels[i*32:(i+1)*32]),hex(c)
        return
    from PIL import ImageFont
    from convert_font import render_glyph
    font_path=next(p for p in Path('/System/Library/Fonts').glob('*.ttc') if unicodedata.normalize('NFC',p.name)=='ヒラギノ角ゴシック W3.ttc')
    face=ImageFont.truetype(str(font_path),16,index=0)
    assert face.getname()==('Hiragino Sans','W3')
    out=['// Generated by generate_japanese.py; Hiragino Sans W3, 16x16, 1bpp.',
         '#pragma once','static const uint16_t language_japanese_codes[] = {',
         ','.join(f'0x{c:04x}' for c in codes),'};',
         'static const uint8_t language_japanese_pixels[][32] = {']
    missing=bytes(render_glyph(face,'\uffff'))
    base=(ROOT/'assets/font16.bin').read_bytes();count=int.from_bytes(base[10:14],'little')
    base_codes=[int.from_bytes(base[14+i*2:16+i*2],'little') for i in range(count)]
    fallback=[]
    for cp in codes:
        glyph=bytes(render_glyph(face,chr(cp)))
        # The language picker preserves each language's native label. Hiragino
        # intentionally lacks the simplified character in 简体中文.
        if glyph==missing and chr(cp)=='简':
            index=base_codes.index(cp);glyph=base[14+count*2+index*32:14+count*2+(index+1)*32];fallback.append(chr(cp))
        assert any(glyph) and glyph!=missing, ('Missing Japanese glyph',chr(cp))
        out.append(' {'+','.join(f'0x{b:02x}' for b in glyph)+'},')
    out+=['};',''];text='\n'.join(out);FONT.write_text(text)
    (DATA/'japanese_glyphs.json').write_text(json.dumps({'font':'Hiragino Sans W3','font_index':0,'size':16,
        'font_sha256':hashlib.sha256(font_path.read_bytes()).hexdigest(),'glyphs':len(codes),'native_label_fallback':fallback,
        'sha256':hashlib.sha256(text.encode()).hexdigest()},indent=2)+'\n')

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    data=generate()
    if a.check:assert OUTPUT.read_text()==data,'Regenerate Japanese catalogue'
    else:OUTPUT.write_text(data)
    font(a.check)
    print(json.dumps({'japanese_strings':len(json.loads((DATA/'ja.json').read_text())), 'glyphs':len(glyph_codes()), 'header_sha256':hashlib.sha256(data.encode()).hexdigest()}))

if __name__=='__main__':main()
